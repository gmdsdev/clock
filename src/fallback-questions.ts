/**
 * Pergunta de cálculo com números sorteados, para o banco offline não ser decorável.
 * Todas têm resultado inteiro e a resposta nunca aparece no texto nem na dica.
 */
export function randomMathQuestion(random: () => number = Math.random): Omit<Question, "id" | "source"> {
  const int = (min: number, max: number) => min + Math.min(max - min, Math.floor(random() * (max - min + 1)));
  const twoDigits = () => {
    const n = int(12, 99);
    return n % 10 === 0 ? n + 1 : n;
  };
  const generators: (() => { text: string; answer: number })[] = [
    () => {
      const a = twoDigits();
      const b = twoDigits();
      return { text: `Quanto é ${a} × ${b}?`, answer: a * b };
    },
    () => {
      const percent = 5 * int(1, 19);
      const base = 20 * int(6, 100);
      return { text: `Quanto é ${percent}% de ${base}?`, answer: (percent * base) / 100 };
    },
    () => {
      const [a, b, c] = [int(100, 999), int(100, 999), int(100, 999)];
      return { text: `Quanto é ${a} + ${b} + ${c}?`, answer: a + b + c };
    },
    () => {
      const b = int(100, 999);
      let a = int(1000, 9999);
      if (a === 2 * b) a += 1;
      return { text: `Quanto é ${a} − ${b}?`, answer: a - b };
    },
    () => {
      const a = int(13, 39);
      return { text: `Quanto é ${a} ao quadrado?`, answer: a * a };
    },
    () => {
      const root = int(12, 31);
      return { text: `Qual é a raiz quadrada de ${root * root}?`, answer: root };
    },
    () => {
      const [a, b, c, d] = [int(10, 99), int(3, 9), int(11, 19), int(1, 9)];
      return { text: `Quanto é ${a} + ${b} × ${c} − ${d}?`, answer: a + b * c - d };
    },
  ];
  const { text, answer } = generators[int(0, generators.length - 1)]();
  return {
    theme: "Matemática",
    text,
    answerType: "number",
    hint: answer === 120 ? "Responda só com o número, ex.: 42" : MATH_HINT,
    expectedAnswer: String(answer),
    acceptedAnswers: [],
    tolerancePercent: 0,
  };
}
